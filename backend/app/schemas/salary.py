from datetime import date, datetime
from decimal import Decimal
from typing import List, Optional

from pydantic import BaseModel, Field, field_validator, model_validator

from app.core.constants import ComponentType, SalaryStatus


class SalaryComponentIn(BaseModel):
    component_type: str
    name: str = Field(min_length=1, max_length=120)
    amount: Decimal = Field(ge=0, max_digits=12, decimal_places=2)
    sort_order: int = 0

    @field_validator("component_type")
    @classmethod
    def _type(cls, v: str) -> str:
        if v not in ComponentType.ALL:
            raise ValueError("component_type must be 'earning' or 'deduction'")
        return v


class SalaryComponentOut(SalaryComponentIn):
    id: int


class SalaryCreate(BaseModel):
    employee_id: int
    period_year: int = Field(ge=2000, le=2100)
    period_month: int = Field(ge=1, le=12)
    working_days: int = Field(ge=0, le=31)
    status: str = SalaryStatus.PENDING
    credit_date: Optional[date] = None
    remarks: Optional[str] = None
    components: List[SalaryComponentIn] = []

    @field_validator("status")
    @classmethod
    def _status(cls, v: str) -> str:
        if v not in SalaryStatus.ALL:
            raise ValueError(f"status must be one of {', '.join(SalaryStatus.ALL)}")
        return v


class SalaryUpdate(BaseModel):
    """Editing an existing salary slip changes its payment details only.

    The employee and the pay period identify the slip and are fixed once it
    exists (generated by hand or automatically); sending them is refused.
    """

    @model_validator(mode="before")
    @classmethod
    def _identity_is_fixed(cls, data):
        if isinstance(data, dict):
            fixed = [k for k in ("employee_id", "period_year", "period_month") if data.get(k) is not None]
            if fixed:
                raise ValueError(
                    "The employee and pay period of an existing salary slip can't be changed; "
                    "only the payment details can be edited."
                )
        return data

    working_days: Optional[int] = Field(None, ge=0, le=31)
    status: Optional[str] = None
    credit_date: Optional[date] = None
    remarks: Optional[str] = None
    components: Optional[List[SalaryComponentIn]] = None


class SalaryCreditRequest(BaseModel):
    credit_date: Optional[date] = None
    attach_payslip: bool = True


class SalaryOut(BaseModel):
    id: int
    employee_id: int
    is_intern: bool = False
    intern_download_allowed: bool = False
    employee_can_view_payslip: bool = False
    employee_can_download_payslip: bool = False
    download_block_reason: Optional[str] = None
    download_request_status: Optional[str] = None
    download_request_id: Optional[int] = None
    download_request_remarks: Optional[str] = None
    can_request_download: bool = False
    employee_name: str
    employee_code: str
    department: Optional[str] = None
    designation: Optional[str] = None
    joining_date: Optional[date] = None
    period_year: int
    period_month: int
    period_label: str
    working_days: int
    status: str
    total_earnings: Decimal
    total_deductions: Decimal
    net_pay: Decimal
    net_pay_display: str
    amount_in_words: str
    credit_date: Optional[date] = None
    credited_at: Optional[datetime] = None
    remarks: Optional[str] = None
    has_payslip: bool = False
    auto_generated: bool = False
    earnings: List[SalaryComponentOut] = []
    deductions: List[SalaryComponentOut] = []


class SalaryCreditResult(BaseModel):
    salary: SalaryOut
    notification_created: bool
    email_sent: bool
    payslip_ready: bool
    detail: str
